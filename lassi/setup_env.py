"""Create a safe first-run `.env` for the simple installer.

No third-party dependency; only stdlib. Existing `.env` is never overwritten.
The generated tokens are printed once; they are not stored anywhere else.
"""

from __future__ import annotations

import os
import secrets
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
ENV_PATH = ROOT / ".env"


def create_env(path: Path, mode: str = "demo") -> dict:
    path = Path(path)
    if path.exists():
        return {"created": False, "path": str(path), "operator": "", "viewer": ""}
    operator = secrets.token_urlsafe(32)
    viewer = secrets.token_urlsafe(32)
    secret = secrets.token_urlsafe(32)
    content = f"""# Generated by the LassiNet installer. Keep this file private.
# Start in demo; switch to live only after `python -m lassi.vet`.
LASSI_MODE={mode}
LASSI_HOST=127.0.0.1
LASSI_PORT=8000
LASSI_AUTO_BLOCK=0
LASSI_TOKEN_OPERATOR={operator}
LASSI_TOKEN_VIEWER={viewer}
LASSI_SECRET={secret}
LASSI_LOG_RETENTION_DAYS=30
# For a live pilot, add:
# LASSI_LIVE_ALLOW=192.168.0.0/24
# LASSI_DRY_RUN=1
# LASSI_FW=mock
"""
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(content, encoding="utf-8")
    try:
        os.chmod(path, 0o600)
    except OSError:
        pass
    return {"created": True, "path": str(path),
            "operator": operator, "viewer": viewer}


def main(argv: list[str] | None = None) -> int:
    args = list(sys.argv[1:] if argv is None else argv)
    path = Path(args[0]) if args else ENV_PATH
    result = create_env(path)
    if not result["created"]:
        print(f"Using existing {result['path']}; tokens were not printed.")
        print("Delete it deliberately if you want to regenerate credentials.")
        return 0
    print(f"Created {result['path']}")
    print("")
    print("  Operator token: " + result["operator"])
    print("  Viewer token:   " + result["viewer"])
    print("")
    print("Open http://127.0.0.1:8000 and sign in with one of them.")
    print("Keep .env private; do not commit or paste the tokens in public.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
